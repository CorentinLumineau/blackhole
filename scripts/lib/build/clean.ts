import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import {
  root,
  AGENTS_BUILD_ROOT,
  CLAUDE_DISTRIBUTION_ROOT,
  DISTRIBUTION_ROOT,
  GEMINI_TARGET_DIRS,
  CODEX_TARGET_DIRS,
  AGENT_PLUGINS_DISTRIBUTION_ROOT,
  AGENT_PLUGINS_TARGET_DIRS,
  DEPRECATED_BUILD_FLAGS,
} from './paths.ts';

/**
 * Step-0 tracking audit: does at least one of `paths` (relative to `rootDir`) contain a
 * git-tracked file? Used to decide whether a build target's opt-in flag can retire (tracked)
 * or must survive (genuinely untracked) — never collapsed onto a hardcoded assumption.
 */
export const isTargetTracked = (rootDir: string, paths: string[]): boolean => {
  for (const p of paths) {
    try {
      const out = execFileSync('git', ['ls-files', '--', p], { cwd: rootDir, encoding: 'utf-8' });
      if (out.trim().length > 0) return true;
    } catch {
      // git invocation failed (e.g. path outside a repo) — treat as untracked, not an error.
    }
  }
  return false;
};

export const cleanDir = (dirPath: string) => {
  if (fs.existsSync(dirPath)) {
    fs.rmSync(dirPath, { recursive: true, force: true });
  }
};

const args = new Set(process.argv.slice(2));

// 1. Resolve deprecated-flag warnings and decide which targets build this run.
export const determineBuildTargets = (
  cliArgs: Set<string> = args
): { buildGemini: boolean; buildCodex: boolean; buildAgentPlugins: boolean } => {
  for (const flag of DEPRECATED_BUILD_FLAGS) {
    if (cliArgs.has(flag)) {
      console.error(
        `[build] ${flag} is deprecated and now a no-op — every git-tracked build target is ` +
          'regenerated by default (ADR-007 T2). Scheduled for removal next release.'
      );
    }
  }

  const geminiTracked = isTargetTracked(root, GEMINI_TARGET_DIRS);
  const codexTracked = isTargetTracked(root, CODEX_TARGET_DIRS);
  const agentPluginsTracked = isTargetTracked(root, AGENT_PLUGINS_TARGET_DIRS);
  if (!geminiTracked) {
    console.error(
      '[build] gemini build targets are not tracked in git — gemini output dirs will be skipped until git-tracked.'
    );
  }
  if (!codexTracked) {
    console.error(
      '[build] codex build targets are not tracked in git — codex output dirs will be skipped until git-tracked.'
    );
  }
  if (!agentPluginsTracked) {
    console.error(
      '[build] agent-plugins build targets are not tracked in git — agent-plugins output dirs will be skipped until git-tracked.'
    );
  }

  // Tracked ⇒ built (ADR-007 T2/R5′). Deprecated CLI flags are ignored for gating — only
  // git tracking decides whether gemini/codex targets compile (deprecation notice above).
  const buildGemini = geminiTracked;
  const buildCodex = codexTracked;
  const buildAgentPlugins = agentPluginsTracked;
  return { buildGemini, buildCodex, buildAgentPlugins };
};

export const cleanBuildDirectories = (buildGemini: boolean, buildCodex: boolean, buildAgentPlugins: boolean) => {
  console.log('Cleaning existing build directories...');
  cleanDir(path.join(root, 'rules'));
  cleanDir(path.join(root, 'agents'));
  cleanDir(path.join(root, 'skills'));
  cleanDir(path.join(root, 'references'));
  cleanDir(path.join(root, '.cursor'));
  // Only clean the subdirs build.ts actually writes — `.claude/` also holds
  // maintainer state (initiatives/, progress.md) that must survive a rebuild.
  // `.claude/skills` is narrowed to the `blackhole/` subdir specifically (issue #267): build only
  // ever writes `.claude/skills/blackhole/`, so wiping the whole `skills/` dir deleted sibling
  // maintainer-only skills (e.g. `create-release/`) that live alongside it. `.claude/agents` and
  // `.claude/rules` still wipe wholesale — narrow them the same way only if maintainer agents/rules
  // are ever added (YAGNI; not done now, since build writes the entirety of both dirs today).
  cleanDir(path.join(root, '.claude', 'agents'));
  cleanDir(path.join(root, '.claude', 'rules'));
  cleanDir(path.join(root, '.claude', 'skills', 'blackhole'));
  // .claude/hooks/ (issue #472) is 100% template-generated by copyHooksDir — safe to wipe and
  // recopy on every build, unlike .claude/settings.json (read-modify-write only, never cleaned).
  cleanDir(path.join(root, '.claude', 'hooks'));
  cleanDir(path.join(root, '.claude-plugin'));
  // Claude marketplace distribution bundle (ADR-009) — unconditional like the rest of Target C
  // above, not gated behind the Gemini/Codex tracked-target opt-in flags: it is the redistributable
  // form of the always-built repo-root .claude/ Target C, not an optional bonus target.
  cleanDir(path.join(root, CLAUDE_DISTRIBUTION_ROOT));
  if (buildGemini) {
    cleanDir(path.join(root, AGENTS_BUILD_ROOT));
    cleanDir(path.join(root, '.gemini-plugin'));
    cleanDir(path.join(root, DISTRIBUTION_ROOT));
  }
  if (buildAgentPlugins) {
    cleanDir(path.join(root, AGENT_PLUGINS_DISTRIBUTION_ROOT));
  }
  if (buildCodex) {
    cleanDir(path.join(root, 'codex-agents'));
    cleanDir(path.join(root, 'codex-skills'));
    cleanDir(path.join(root, '.codex-plugin'));
  }
  if (fs.existsSync(path.join(root, 'SKILL.md'))) {
    fs.unlinkSync(path.join(root, 'SKILL.md'));
  }
  if (buildCodex && fs.existsSync(path.join(root, 'codex-marketplace.json'))) {
    fs.unlinkSync(path.join(root, 'codex-marketplace.json'));
  }
};
